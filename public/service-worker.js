const CACHE_NAME = 'mtm-pwa-v0.0.1';
const urlsToCache = [
  '/',
  'assets\index-B8wrhbJA.js',
  'assets\index-D8jHm0lM.css',
  'assets\ort.min-Dhy2wKlY.js',
  'assets\piper-DeOu3H9E-VFBVHF2w.js',
  'assets\vits-web-mWKhNpVd.js.map',
  'icon-192x192.png',
  'icon-512x512.png',
  'index.html',
  'manifest.json',
  'service-worker.js',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => {
        console.log('Opened cache');
        return cache.addAll(urlsToCache);
      })
      .then(() => self.skipWaiting())
  );
});
